# ativando e desativando o ambiente virtual - venv

'''
Verificar versão do python:
    python -V
    python --version

Verificar qual ambiente do Python está sendo utilizado (global ou virtual) no Windows:
    gcm python
    gcm python --Syntax
Verificar qual ambiente do Python está sendo utilizado (global ou virtual) no Linux / MAC:
    which python

Criar ambiente virtual:
    python -m venv venv

Ativar o ambiente virtual (Windows):
    venv\Scripts\activate

Ativar o ambiente virtual (Linux / MAC):
    source venv/bin/activate

Desativar o ambiente virtual (Windows / Linux / MAC):
    deactivate

'''