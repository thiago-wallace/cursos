# pip - instalando pacotes e bibliotecas.py

'''
pip - gerenciador de pacotes do python
https://pypi.org/

Instalar pacotes (Exemplo: instalando o pacote PyMySQL):
    pip install pymysql
    python -m pip install pymysql

Atualizar o pip
    python -m pip install pip --upgrade
    pip install pip --upgrade

Desinstalar pacotes (Exemplo: desinstalando o pacote PyMySQL):
    pip uninstall pymysql

Consultar pacotes instalados:
    pip freeze

Verificar versões disponíveis de um determinado pacote:
    pip index versions pymysql

Instalar determinada versão de um pacote (Exemplo: instalando o pacote PyMySQL versão 1.0.2):
    pip install pymysql==1.0.2

'''
