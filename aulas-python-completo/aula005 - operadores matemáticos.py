# Operadores matemáticos

adicao = 10 + 3
print("Adição: ", adicao)

subtracao = 10 - 3
print("subtração: ", subtracao)

multiplicacao = 10 * 3
print("Multiplicação: ", multiplicacao)

divisao = 10 / 3
print("Divisão: ", divisao)

divisao_inteira = 10 // 3 # Retorna apenas o quonciente
print("Divisão inteira: ", divisao_inteira)

potencia = 10 ** 3 # Forma 1: usando **
print("Potência: ", potencia)

modulo = 10 % 3 # Retorna apenas o resto da divisão
print("Módulo: ", modulo)

potencia2 = pow(10,3) # Forma 2: usando função pow()
print("Potência: ", potencia2)
