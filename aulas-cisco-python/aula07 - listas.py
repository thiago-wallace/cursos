# lista
amigos = ['Marcos', 'Pedro', 'Adriana', 'Karina', 'Júlia']
# exibir lista inteira
print(amigos)
# exibir o index 2 da lista
print(amigos[2])
# exibir o index -3 da lista, ou seja, o 3 de trás para frente
print(amigos[-3])
# exibir os index do 1 ao 3 (sem incluir o 3)
print(amigos[1:3])
# exibir a lista a partir do index 2
print(amigos[2:])
# editar o índice 1 da lista
amigos[1] = 'João'
print(amigos)
