nome = 'Marcos da Silva'
#       0123456789012345

# \n - pular linha
print('Marcos \nda Silva')
# \' Adicionar aspas
print('Marcos \'da Silva')
# concatenação com +
print(nome + ' tem 19 anos de idade')
# função para deixar as letras em caixa alta
print(nome.upper())
# função para deixar as letras em caixa baixa
print(nome.lower())
# função para retornar o tamanho da string
print(len(nome))
# verificar um caractere da string pelo index 13
print(nome[13])
# verificar em qual index começa 'da'
print(nome.index('da'))
# conta a quantidade de letras 'a' na string
print(nome.count('a'))
